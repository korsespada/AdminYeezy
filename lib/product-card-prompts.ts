/**
 * Собирает системный промпт запроса: базовые требования, инструкция поставщика
 * и обязательные правила каталога.
 */
export function composeCardSystemPrompt(input: {
  base: string
  supplierPrompt?: string | null
  catalogRules?: string | null
}) {
  return [
    input.base,
    String(input.supplierPrompt || '').trim() ? `Инструкция поставщика:\n${String(input.supplierPrompt).trim()}` : '',
    String(input.catalogRules || '').trim(),
  ].filter(Boolean).join('\n\n')
}
