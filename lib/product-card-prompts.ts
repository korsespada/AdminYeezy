/**
 * Промпт поставщика для обработки уже опубликованных карточек.
 *
 * Хранится отдельно от инструкций «Выгрузок»: там правило описывает разбор
 * сырой китайской карточки, а здесь — правку опубликованного товара каталога.
 * Эффективный системный промпт собирается из базовых требований, инструкции
 * поставщика и обязательных правил каталога.
 */

/** Повторяющиеся особенности карточек Hermes, которые оператор может править. */
export const HERMES_CARD_PROMPT_DEFAULT = `Поставщик Hermes (сумки и обувь). Особенности источника:
- Блок характеристик: «Стиль», «Цвет», «Материал»/«Кожа», «Размер», «Фурнитура», затем текст «Описание».
- Цвет указывай во внутренней форме Hermes: код и имя через слэш («18/Etoupe», «89/Noir», «0V/Gris Ciment»). Если в исходнике русское название и код в скобках («Черный (ck89/noir)»), в описании дай оба: «чёрный (ck89/Noir)».
- Модель пиши без размера: «Birkin», «Kelly», «Lindy», «24/24 Mini»; размер отдельно («Birkin 25»).
- Материал сохраняй точно: Swift, Togo, Epsom, Chèvre, Clémence, Box, Evercolor, аллигатор, крокодил, страус, ящерица. Не заменяй общим словом «кожа» и не путай кожу верха с подкладкой.
- Фурнитуру указывай только подтверждённую: серебро, золото, палладий, розовое золото.
- Для сумок габариты в формате «26 × 18 × 12 см», для обуви размерный ряд «34–41».
- Подошва у обуви этого поставщика не кожаная: она резиновая или с кожаной набойкой. Если снизу видна кожа, это стелька, а не подошва.
- Не переноси: «из Франции», «заказ клиента», «высшего класса», «1:1», эмодзи, цены, сроки, условия возврата и обмена, «полностью ручная работа».
- Альты: бренд Hermes, модель, цвет и ракурс кадра; коробку, упаковку, пакет, подложку и фон не упоминай.`

/** Подсказка по умолчанию для пресета: у каждого поставщика она своя. */
export function defaultCardPromptForPreset(presetKey: string) {
  if (presetKey === 'hermes') return HERMES_CARD_PROMPT_DEFAULT
  return ''
}

/** Комплектация по умолчанию: у каждого поставщика своя. */
export function defaultPackagingForPreset(presetKey: string) {
  if (presetKey === 'hermes') return HERMES_PACKAGING_DEFAULT
  return ''
}

