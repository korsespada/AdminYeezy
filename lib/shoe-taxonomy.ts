export function canonicalShoeSubcategoryName(value: unknown) {
  return SHOE_SUBCATEGORY_ALIASES.get(normalizeShoeTaxonomyName(value)) || ''
}

export function isGenericShoeSubcategory(value: unknown) {
  return normalizeShoeTaxonomyName(value) === 'туфли'
}

export function filterShoeSubcategoriesForAi<T extends { id: string; name: string }>(subcategories: T[]) {
  return subcategories.filter((subcategory) => !isGenericShoeSubcategory(subcategory.name))
}

export function inferGenericShoeSubcategoryName(value: unknown) {
  const text = normalizeShoeTaxonomyName(value)
  if (!text) return 'Туфли на плоской подошве'

  const explicitlyFlat = [
    /без.{0,24}каблук/,
    /плоск(?:ая|ой|ую|ие|их|ом) подошв/,
    /низкий ход/,
    /\bflat(?:s)?\b/,
    /平底/,
  ].some((pattern) => pattern.test(text))
  if (explicitlyFlat) return 'Туфли на плоской подошве'

  const hasHeel = [
    /каблук/,
    /шпильк/,
    /лодочк/,
    /\bpumps?\b/,
    /\bhigh heels?\b/,
    /\bstiletto\b/,
    /高跟/,
    /细跟/,
    /粗跟/,
  ].some((pattern) => pattern.test(text))
  return hasHeel ? 'Туфли на каблуке' : 'Туфли на плоской подошве'
}

export function inferShoeSlingbackSubcategoryName(value: unknown) {
  const text = normalizeShoeTaxonomyName(value)
  const hasSlingbackConstruction = [
    /слингбэк/,
    /\bslingbacks?\b/,
    /ремеш(?:ок|ком)\s+(?:на\s+)?пятк/,
    /ремеш(?:ок|ком)[^.!?]{0,36}(?:сзади|задн)/,
    /\b(?:heel|back)[ -]?strap\b/,
    /露跟(?:高跟鞋|鞋)/,
  ].some((pattern) => pattern.test(text))
  if (!hasSlingbackConstruction) return ''
  const hasOpenToe = [
    /открыт[^.!?]{0,24}(?:мыс|нос)/,
    /\bopen[- ]toe\b/,
    /露趾/,
    /凉鞋/,
  ].some((pattern) => pattern.test(text))
  if (hasOpenToe) return ''

  const hasHeel = [
    /каблук/,
    /шпильк/,
    /лодочк/,
    /\bpumps?\b/,
    /\bhigh heels?\b/,
    /stiletto/,
    /高跟/,
    /逗号跟/,
  ].some((pattern) => pattern.test(text))
  return hasHeel ? 'Туфли на каблуке' : 'Туфли на плоской подошве'
}

function normalizeShoeTaxonomyName(value: unknown) {
  return String(value || '')
    .trim()
    .toLocaleLowerCase('ru-RU')
    .replace(/ё/g, 'е')
    .replace(/[‐‑‒–—-]+/g, ' ')
    .replace(/\s+/g, ' ')
}
