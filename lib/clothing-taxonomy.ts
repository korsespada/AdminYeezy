function normalize(value: unknown) {
  return String(value || '')
    .trim()
    .toLocaleLowerCase('ru-RU')
    .replace(/ё/g, 'е')
    .replace(/[‐‑‒–—-]+/g, ' ')
    .replace(/\s+/g, ' ')
}
