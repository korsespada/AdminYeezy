// Служебные обороты описания не называют тип товара: «сочетается с
// футболками», «подобрать под брюки», «комфорт в носке». Поэтому в прозе
// принимается только упоминание типа без предлога или союза перед ним.
const PROSE_BLOCKING_PREFIX = new Set([
  'с', 'со', 'и', 'или', 'как', 'под', 'подо', 'из', 'на', 'к', 'ко', 'по', 'для', 'от', 'до',
  'в', 'во', 'без', 'кроме', 'вместо', 'вроде', 'типа', 'а', 'но', 'также', 'вместе', 'плюс',
  'над', 'за', 'при', 'о', 'об', 'через', 'между', 'перед', 'после',
])

function standaloneMention(text: string, pattern: RegExp) {
  const flags = pattern.flags.includes('g') ? pattern.flags : `${pattern.flags}g`
  const scan = new RegExp(pattern.source, flags)
  let match: RegExpExecArray | null
  while ((match = scan.exec(text))) {
    // Предлог или союз может стоять не вплотную к типу: «как с базовыми
    // футболками», «под широкие брюки». Поэтому проверяются три слова перед.
    const before = text.slice(0, match.index).trim().split(/\s+/).filter(Boolean).slice(-3)
    const blocked = before.some((word) => PROSE_BLOCKING_PREFIX.has(word))
    if (!blocked) return match
    if (scan.lastIndex === match.index) scan.lastIndex += 1
  }
  return null
}

function inferFromText(text: string, prose: boolean) {
  const accept = (pattern: RegExp) => (prose ? Boolean(standaloneMention(text, pattern)) : pattern.test(text))
  if (isShearlingOuterwear(text) && accept(/(дубленк|shearling|sheepskin|овчин|羊皮毛一体|皮毛一体)/u)) {
    return 'Дублёнки'
  }
  const compoundJacket = /(куртк[а-яё]*\s+рубашк|рубашк[а-яё]*\s+куртк|куртк[а-яё]*\s+пиджак|пиджак[а-яё]*\s+куртк)/u
  if (accept(compoundJacket)) return outerwearSubcategory(text) || 'Куртки'
  // Худи из кожи или замши — верхняя одежда, а не трикотаж.
  if (accept(/(худи|толстовк|свитшот)/u) && LEATHER_WORD.test(text)) return 'Кожаные куртки'
  // Вязаный жакет с планкой и пуговицами — это кардиган, а не костюмный жакет.
  if (accept(/(вязан|трикотажн|кашемиров|вязк)[а-яё]*\s+(?:\S+\s+)?жакет/u)) return 'Кардиганы'
  if (accept(/(皮衣|皮夹克|麂皮|翻毛皮)/u)) return 'Кожаные куртки'
  const beforeOuterwear = RULES_BEFORE_OUTERWEAR.find(([pattern]) => accept(pattern))
  if (beforeOuterwear) return beforeOuterwear[1]
  if (accept(OUTERWEAR_NOUN)) return outerwearSubcategory(text) || 'Куртки'
  const afterOuterwear = RULES_AFTER_OUTERWEAR.find(([pattern]) => accept(pattern))
  return afterOuterwear?.[1] || ''
}

export function inferClothingSubcategoryName(value: unknown) {
  const text = normalize(value)
  if (!text) return ''
  return inferFromText(text, false)
}

// Разбор описания допустим только как последняя подсказка: заголовок товара
// всегда точнее прозы, где соседние вещи упоминаются как образ или сочетание.
export function inferClothingSubcategoryNameFromProse(value: unknown) {
  const text = normalize(value)
  if (!text) return ''
  return inferFromText(text, true)
}

function normalize(value: unknown) {
  return String(value || '')
    .trim()
    .toLocaleLowerCase('ru-RU')
    .replace(/ё/g, 'е')
    .replace(/[‐‑‒–—-]+/g, ' ')
    .replace(/\s+/g, ' ')
}
